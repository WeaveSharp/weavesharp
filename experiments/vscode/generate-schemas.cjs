const { readdirSync, readFileSync, writeFileSync } = require("node:fs");
const { resolve, join } = require("node:path");

const root = resolve(__dirname, "../..");
function schemaModule() {
  const directory = join(root, "protocol/v0");
  const entries = readdirSync(directory).filter((name) => name.endsWith(".schema.json")).sort()
    .map((name) => [name, JSON.parse(readFileSync(join(directory, name), "utf8"))]);
  return "// Generated by generate-schemas.cjs from protocol/v0.\n" +
    "export const schemas: ReadonlyMap<string, unknown> = new Map<string, unknown>(" +
    JSON.stringify(entries, null, 2) + ");\n";
}
exports.schemaModule = schemaModule;
if (require.main === module) {
  writeFileSync(join(__dirname, "src/schemas.generated.ts"), schemaModule());
}
